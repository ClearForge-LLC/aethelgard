//! `verify --fab-out OUT --rebind COMMITTED` (`AET-WO-4300k`, ruled
//! 2026-11-24T11:25Z): a committed package re-bound to its specification
//! after a change that moves no hardware byte (a specification version
//! literal). The readiness gate is not judged. Instead the package derived as
//! `--fab-out` derives it must equal `COMMITTED` byte for byte, but for what
//! binds it: in `MANIFEST.json`, the lines holding `specification_sha256`,
//! `topology_sha256`, `verdict_sha256`, each scenario's `sha256` and
//! `FAB-NOTES.md`'s hash; in `FAB-NOTES.md`, the specification sha256 line,
//! and the `Generated by aethelgard <version>` line, but only to this
//! engine's own version (`AET-WO-1802` Q1, ruled 2026-11-26T20:19Z: every
//! other file was just re-derived byte-equal, so the engine named does make
//! these bytes). Any other moved byte (a Gerber, the BOM, the ELF, a precondition row, a
//! key's order or spacing) refuses it, and nothing is written. Every file is
//! read as `--against-fab` reads one ([`crate::tree::against`]): never through
//! a symlink, a regular file only, the entries capped. A new board has no
//! committed package, so it cannot re-bind; that the directory is the one
//! committed is the caller's (CI pins `fab/sentinel-01-bench/package`).

use std::collections::BTreeMap;
use std::path::Path;

use aethelgard_cli::identity::VERSION;

use crate::run::Stop;
use crate::tree;

/// `COMMITTED` holds no committed package.
pub const NO_PACKAGE: &str = "RebindNoPackage";
/// `COMMITTED`'s package is another board's.
pub const OTHER_BOARD: &str = "RebindOtherBoard";
/// The derived package moves more than its binding.
pub const MOVED: &str = "RebindMoved";

const MANIFEST: &str = "MANIFEST.json";
const NOTES: &str = "FAB-NOTES.md";
/// The `MANIFEST.json` keys whose value lines a re-bind may move (M1, ruled
/// 12:45Z): the specification's sha256, the topology's, which carries the
/// specification's sha256 and so moves with every bump (measured on
/// Sentinel-01's re-bind), and the verdict's, which names both. The ELF and
/// every hardware file move nothing: a moved one refuses.
const BINDING: [&str; 3] = ["specification_sha256", "topology_sha256", "verdict_sha256"];
/// The line before `FAB-NOTES.md`'s specification sha256.
const NOTES_LEAD: &str = "from the specification whose sha256 is";
/// The start of that line, before the engine's version (`fab.rs`).
const NOTES_ENGINE: &str = "Generated by aethelgard ";
/// The most a committed `MANIFEST.json` or `FAB-NOTES.md` may hold.
const MAX_TEXT: u64 = 1 << 20;

fn none(dir: &Path, why: String) -> Stop {
    Stop::refused(
        NO_PACKAGE,
        format!(
            "no package: {} holds no committed package to re-bind ({why})",
            dir.display()
        ),
    )
}

/// `dir`'s `name`, a regular file read without following a symlink.
fn text_of(dir: &Path, name: &str) -> Result<Vec<u8>, Stop> {
    tree::regular(&dir.join(name), MAX_TEXT)
        .map_err(|s| none(dir, s.message))?
        .ok_or_else(|| {
            none(
                dir,
                format!("{name} is not a regular file of at most {MAX_TEXT} bytes"),
            )
        })
}

/// Before any gate: `dir` holds a committed package, and it is `project`'s.
pub fn committed(dir: &Path, project: &str) -> Result<(), Stop> {
    crate::input::dir_check(dir)?;
    let bytes = text_of(dir, MANIFEST)?;
    let v: serde_json::Value = serde_json::from_slice(&bytes)
        .map_err(|e| none(dir, format!("{MANIFEST} is not JSON: {e}")))?;
    match v["project"].as_str() {
        None => Err(none(dir, format!("{MANIFEST} names no project"))),
        Some(p) if p == project => Ok(()),
        Some(p) => Err(Stop::refused(
            OTHER_BOARD,
            format!(
                "no package: {} is the package of `{p}`, not of `{project}`: a re-bind keeps its board",
                dir.display()
            ),
        )),
    }
}

/// After every gate: `derived` (every file, `MANIFEST.json` included) equals
/// the package in `dir` but for its binding, or the re-bind is refused,
/// naming each moved file.
pub fn matches(dir: &Path, derived: &BTreeMap<String, Vec<u8>>) -> Result<(), Stop> {
    let mut moved = Vec::new();
    let mut expected = derived.clone();
    for (name, alike) in [
        (MANIFEST, manifest_bound_alike as fn(&str, &str) -> bool),
        (NOTES, |h: &str, d: &str| notes_bound_alike(h, d, VERSION)),
    ] {
        let held = text_of(dir, name)?;
        let ours = derived.get(name).map_or(&[][..], Vec::as_slice);
        match (std::str::from_utf8(&held), std::str::from_utf8(ours)) {
            // `AET-WO-4310` (4), (5), ruled 2026-11-27T08:22Z (2): the lines
            // a re-bind admits are left out of both before the comparison,
            // and nothing else is.
            (Ok(h), Ok(d)) if alike(&admitted(name, h, h), &admitted(name, h, d)) => {
                // Judged here; the walk below sees the committed bytes.
                expected.insert(name.to_owned(), held);
            }
            _ => moved.push(format!("{name} differs beyond its binding")),
        }
    }
    for d in tree::against(dir, &expected, &[])? {
        moved.push(match d {
            tree::Difference::Missing(p) => format!("{p} is not in the committed package"),
            tree::Difference::Extra(p) => format!("{p} is not derived"),
            tree::Difference::Differs(p) => format!("{p} differs"),
        });
    }
    if moved.is_empty() {
        return Ok(());
    }
    Err(Stop::refused(
        MOVED,
        format!(
            "no package: re-binding {} would move more than its binding: {}; a re-bind moves only MANIFEST.json's {}, scenario and FAB-NOTES.md hash lines, FAB-NOTES.md's specification line, and its engine line to this engine's version ({VERSION})",
            dir.display(),
            moved.join("; "),
            BINDING.join(", ")
        ),
    ))
}

/// The FAB-NOTES lines a re-bind admits, by key (`AET-WO-4310` (4)).
const ADMITTED_NOTES: [&str; 2] = [crate::fab::OUTLINE_KEY, crate::fab::LADDER_KEY];

/// `text` (the package's `name`) less what a re-bind admits against the
/// committed `held` (`AET-WO-4310` (4), (5), ruled 2026-11-27T08:22Z (2)):
/// in `FAB-NOTES.md`, the outline and capacitance ladder lines, by key; in
/// `MANIFEST.json`, each scenario entry whose scenario `held` does not name
/// (the scenarios D7 adds). Every other line stays, and must be equal.
fn admitted(name: &str, held: &str, text: &str) -> String {
    match name {
        // A key the committed notes already state is compared as every other
        // line is (adversarial F10 (b)): only a key they lack is admitted.
        NOTES => text
            .split_inclusive('\n')
            .filter(|l| {
                !ADMITTED_NOTES
                    .iter()
                    .any(|k| l.starts_with(k) && !held.lines().any(|h| h.starts_with(k)))
            })
            .collect(),
        MANIFEST => without_new_scenarios(held, text),
        _ => text.to_owned(),
    }
}

/// `manifest` with every entry of its `scenarios` array whose scenario
/// `held` does not name left out, the array's commas rejoined; unchanged
/// when either is not the shape the writer gives (the comparison then
/// refuses it as it stands).
fn without_new_scenarios(held: &str, manifest: &str) -> String {
    let Ok(h) = serde_json::from_str::<serde_json::Value>(held) else {
        return manifest.to_owned();
    };
    let names: std::collections::BTreeSet<&str> = h["scenarios"]
        .as_array()
        .into_iter()
        .flatten()
        .filter_map(|s| s["scenario"].as_str())
        .collect();
    let lines: Vec<&str> = manifest.split('\n').collect();
    let Some(start) = lines.iter().position(|l| *l == "  \"scenarios\": [") else {
        return manifest.to_owned();
    };
    let Some(end) = lines[start..]
        .iter()
        .position(|l| *l == "  ]," || *l == "  ]")
        .map(|e| start + e)
    else {
        return manifest.to_owned();
    };
    // Each entry is exactly four lines, as `to_vec_pretty` writes it.
    let body = &lines[start + 1..end];
    if !body.len().is_multiple_of(4) {
        return manifest.to_owned();
    }
    let kept: Vec<&[&str]> = body
        .chunks(4)
        .filter(|e| {
            e[1].trim_start()
                .strip_prefix("\"scenario\": \"")
                .and_then(|r| r.strip_suffix("\","))
                .is_none_or(|n| names.contains(n))
        })
        .collect();
    let mut out: Vec<String> = lines[..=start].iter().map(|l| (*l).to_owned()).collect();
    for (i, e) in kept.iter().enumerate() {
        out.extend(e[..3].iter().map(|l| (*l).to_owned()));
        let close = e[3].trim_end_matches(',');
        out.push(if i + 1 < kept.len() {
            format!("{close},")
        } else {
            close.to_owned()
        });
    }
    out.extend(lines[end..].iter().map(|l| (*l).to_owned()));
    out.join("\n")
}

/// Before any gate (`AET-WO-4310` (4)): the committed package in `dir`
/// states what its board was built at, or `verify --against-fab` refuses
/// it by name, naming each line it lacks.
pub fn states_built(dir: &Path) -> Result<(), Stop> {
    let notes = text_of(dir, NOTES)?;
    let text = String::from_utf8_lossy(&notes);
    let lacking: Vec<&str> = ADMITTED_NOTES
        .iter()
        .copied()
        .filter(|k| !text.lines().any(|l| l.starts_with(k)))
        .collect();
    if lacking.is_empty() {
        return Ok(());
    }
    Err(Stop::refused(
        "PackageBuiltUnstated",
        format!(
            "no package: {}'s {NOTES} states no {}: a package names its outline and its capacitance ladder as built (AET-WO-4310 (4)); write it again",
            dir.display(),
            lacking
                .iter()
                .map(|k| format!("`{}`", k.trim_end()))
                .collect::<Vec<_>>()
                .join(" and ")
        ),
    ))
}

/// `"<key>": "<64 hex>"` with its indent and its trailing comma, if any.
fn hash_line(line: &str) -> Option<(&str, &str, &str)> {
    let body = line.trim_start();
    let indent = &line[..line.len() - body.len()];
    let (body, comma) = body.strip_suffix(',').map_or((body, ""), |b| (b, ","));
    let (key, value) = body.strip_prefix('"')?.split_once("\": \"")?;
    let hex = value.strip_suffix('"')?;
    hex64(hex).then_some((indent, key, comma))
}

/// `MANIFEST.json` alike, line for line, but for a binding hash line: one of
/// [`BINDING`], a scenario's `sha256` (the line after its equal `scenario`
/// line), or `FAB-NOTES.md`'s, each with the same key, indent and comma.
fn manifest_bound_alike(held: &str, derived: &str) -> bool {
    let (h, d): (Vec<&str>, Vec<&str>) =
        (held.split('\n').collect(), derived.split('\n').collect());
    h.len() == d.len()
        && h.iter().zip(&d).enumerate().all(|(i, (a, b))| {
            a == b
                || match (hash_line(a), hash_line(b)) {
                    (Some(x), Some(y)) if x == y => {
                        BINDING.contains(&x.1)
                            || x.1 == NOTES
                            || (x.1 == "sha256"
                                && i > 0
                                && h[i - 1] == d[i - 1]
                                && h[i - 1].trim_start().starts_with("\"scenario\": "))
                    }
                    _ => false,
                }
        })
}

/// `FAB-NOTES.md` alike, line for line, but for the 64-hex line after
/// [`NOTES_LEAD`], and that lead's engine line moved to `engine`.
fn notes_bound_alike(held: &str, derived: &str, engine: &str) -> bool {
    let (h, d): (Vec<&str>, Vec<&str>) =
        (held.split('\n').collect(), derived.split('\n').collect());
    let line_alike = |a: &str, b: &str| a == b || engine_line(a, b, engine);
    h.len() == d.len()
        && h.iter().zip(&d).enumerate().all(|(i, (a, b))| {
            line_alike(a, b)
                || (i > 0
                    && line_alike(h[i - 1], d[i - 1])
                    && h[i - 1].trim_end().ends_with(NOTES_LEAD)
                    && sha_line(a)
                    && sha_line(b))
        })
}

/// `Generated by aethelgard <version> <NOTES_LEAD>` in both, `derived`'s
/// version `engine` and `held`'s any one word of printable ASCII.
fn engine_line(held: &str, derived: &str, engine: &str) -> bool {
    engine_version(derived) == Some(engine) && engine_version(held).is_some()
}

/// The version in `Generated by aethelgard <version> <NOTES_LEAD>`.
fn engine_version(line: &str) -> Option<&str> {
    line.strip_prefix(NOTES_ENGINE)?
        .strip_suffix(NOTES_LEAD)?
        .strip_suffix(' ')
        .filter(|v| !v.is_empty() && v.bytes().all(|b| b.is_ascii_graphic()))
}

/// "`<64 lowercase hex>`." and nothing else.
fn sha_line(line: &str) -> bool {
    line.strip_prefix('`')
        .and_then(|l| l.strip_suffix("`."))
        .is_some_and(hex64)
}

/// 64 lowercase hex digits, a sha256.
fn hex64(hex: &str) -> bool {
    hex.len() == 64 && hex.bytes().all(|c| matches!(c, b'0'..=b'9' | b'a'..=b'f'))
}

