#!/usr/bin/env python3
"""AET-WO-1313 §1.1: Sentinel-03 as far as main can say it, at four layers.

Starts from V5, regenerated by `2b43672`'s spike/3400/make_variants.py (AET-WO-3401 deletes it from
the tree; it is read from git), and adds only what main can declare:
  - the flight sensors on their own footprints (AET-WO-4220b), grafted from sentinel-02-own.json:
    the ICM-42688-P U5 on its own SPI bus `IMU` (SCK pinned PB13 there; its CS pinned PB12 here),
    the BMP581 U7 on `SENSORS`;
  - AET-WO-1312's bench access: a test point on every declared net, plus one GND (main refuses a second); BOOT0 on J2 pin 2
    (free on V5); mcu.reset_switch;
  - four layers: four-layer.json's `board`, replaced whole.
Nothing is edited that V5 declares, except J2 pin 2 (unassigned on V5) and the project name.

Run from the repository root:  python3 -I spike/1313/make_fixture.py [OUT [V5_4L_OUT]]
OUT defaults to crates/aethelgard-cli/tests/fixtures/sentinel-03.json.
"""
import copy
import json
import pathlib
import subprocess
import sys
import types

ROOT = pathlib.Path.cwd()
OUT = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "crates/aethelgard-cli/tests/fixtures/sentinel-03.json"
OWN = ROOT / "crates/aethelgard-cli/tests/fixtures/sentinel-02-own.json"
FOUR = ROOT / "crates/aethelgard-cli/tests/fixtures/four-layer.json"
EXAMPLE = ROOT / "examples/sentinel-01-minimal.json"
VARIANTS_AT = "2b43672"


def variants():
    src = subprocess.run(["git", "show", f"{VARIANTS_AT}:spike/3400/make_variants.py"],
                         check=True, capture_output=True, text=True).stdout
    mod = types.ModuleType("make_variants")
    mod.__dict__["__file__"] = "make_variants.py"
    exec(compile(src, f"{VARIANTS_AT}:spike/3400/make_variants.py", "exec"), mod.__dict__)
    return mod


def declared_nets(v):
    """Every net the specification declares by name, in a fixed order (buses, devices' chip selects,
    serial ports, motors, connectors' named nets, the domains), each once."""
    seen = []

    def add(n):
        if n and n != "GND" and n not in seen:
            seen.append(n)
    for b in v["i2c_buses"]:
        add(b["sda"]["net"]); add(b["scl"]["net"])
    for b in v["spi_buses"]:
        for k in ("sck", "mosi", "miso"):
            add(b[k]["net"])
    for d in v["spi_devices"]:
        add(d["cs"]["net"])
    for s in v["serial_ports"]:
        add(s["tx"]["net"]); add(s["rx"]["net"])
    for m in v["motor_outputs"]:
        add(m["label"])
    for c in v["connectors"]:
        for p in c["pins"]:
            add(p["net"])
    for d in v["voltage_domains"]:
        add(d["id"])
    return seen


def main():
    mv = variants()
    base = json.loads(EXAMPLE.read_text())
    v = mv.v5(base)
    own = json.loads(OWN.read_text())
    # The flight sensors (4220b), as sentinel-02-own.json declares them.
    v["spi_buses"].append(copy.deepcopy(next(b for b in own["spi_buses"] if b["id"] == "IMU")))
    u5 = copy.deepcopy(next(d for d in own["spi_devices"] if d["reference"] == "U5"))
    # A constraint added, none dropped (3400's practice): IMU_CS on PB12, SPI2's NSS pin, beside SCK,
    # MISO and MOSI (PB13-PB15, LQFP-144 pads 73-76). Measured unpinned (FEEDBACK §2.1): the solver puts
    # IMU_CS on pad 35, across the MCU, the placer seats U5 by that pad (the first shared label net), and
    # IMU_SCK and IMU_MOSI exceed their declared 30 pF in `extract` under today's placer.
    u5["cs"]["pin"] = "PB12"
    v["spi_devices"].append(u5)
    v["i2c_devices"].append(copy.deepcopy(next(d for d in own["i2c_devices"] if d["reference"] == "U7")))
    v["net_constraints"] += [copy.deepcopy(k) for k in own["net_constraints"] if k["net_name"].startswith("IMU_")]
    # Bench access (1312): BOOT0 on J2 pin 2, the reset switch, a test point on every declared net.
    j2 = next(c for c in v["connectors"] if c["reference"] == "J2")
    assert j2["pins"][1]["pin"] == "2" and j2["pins"][1]["net"] is None, j2
    j2["pins"][1]["net"] = "BOOT0"
    v["mcu"]["reset_switch"] = True
    nets = declared_nets(v)
    v["test_points"] = [{"net": n, "reference": f"TP{i + 1}"} for i, n in enumerate(nets)]
    # The work order asks for two GND test points; 1312 refuses a net's second test point
    # (`TestPointNetRepeated`, measured), so main can say one. FEEDBACK names the second.
    v["test_points"].append({"net": "GND", "reference": f"TP{len(nets) + 1}"})
    # Four layers (4100), the board replaced whole.
    v["board"] = copy.deepcopy(json.loads(FOUR.read_text())["board"])
    v["project_name"] = "sentinel-03"
    OUT.write_text(json.dumps(v, indent=2) + "\n")
    if len(sys.argv) > 2:  # V5 at four layers, for §1.2's comparison
        v5 = mv.v5(json.loads(EXAMPLE.read_text()))
        v5["board"] = copy.deepcopy(json.loads(FOUR.read_text())["board"])
        v5["project_name"] += "-4l"
        pathlib.Path(sys.argv[2]).write_text(json.dumps(v5, indent=2) + "\n")
    print(f"wrote {OUT}: {len(v['test_points'])} test points", file=sys.stderr)


if __name__ == "__main__":
    main()
