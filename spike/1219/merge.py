"""AET-WO-1219: build classes.tsv from the workers' lenses and the reviewer's
overrides, and name every disagreement between the two lenses.

  lens1/<unit>.tsv   the first worker per unit (K, R, Hc, Hs, T), every entry
  lens2/<unit>.tsv   the blind second lens (K2, R2, Hc2): a subset, not shown lens 1
  overrides.tsv      the reviewer's decisions, each with its reason; they win

The four table-level H rows are computed by RULES §3 from their columns:
S when any column is S (naming them), else D.
Writes classes.tsv and out/disagreements.md.
"""
import csv
import json
import pathlib
import sys

here = pathlib.Path(__file__).parent
HDR = ["id", "class", "flag", "tags", "value_at", "reason"]


def read(p):
    if not p.exists():
        return {}
    rows = list(csv.reader(p.open(), delimiter="\t", quoting=csv.QUOTE_NONE))
    assert rows[0] == HDR, (p, rows[0])
    out = {}
    for r in rows[1:]:
        if not r:
            continue
        assert len(r) == 6, (p, r)
        assert r[0] not in out, (p, "twice", r[0])
        out[r[0]] = r
    return out


lens1 = {}
inv = json.loads((here / "out" / "inventory.json").read_text())
shared = set(inv["T_shared_with_K"])
for u in ["K", "R", "Hc", "Hs", "T"]:
    for i, r in read(here / "lens1" / (u + ".tsv")).items():
        if u == "T" and i in shared:
            continue  # reachable from the specification: K's row is the one (RULES §1)
        assert i not in lens1, i
        lens1[i] = r
lens2 = {}
for u in ["K2", "R2", "Hc2"]:
    lens2.update(read(here / "lens2" / (u + ".tsv")))
over = read(here / "overrides.tsv")

final = dict(lens1)
final.update(over)

# Table-level H rows from their columns (RULES §3).
for h in inv["H"]:
    if h["id"].count(":") == 2:
        continue  # a source item, classed by a worker
    cols = [c for c in inv["H_columns"] if c["id"].startswith(h["id"] + "|")]
    s_cols = [c["id"].split("|", 1)[1] for c in cols if final[c["id"]][1] == "S"]
    if s_cols:
        final[h["id"]] = [h["id"], "S", "", "", "-", "RULES §3: S columns " + ", ".join(s_cols)]
    else:
        final[h["id"]] = [h["id"], "D", "", "", "-", "RULES §3: every column V or N; a second vendor adds rows"]

with (here / "classes.tsv").open("w") as f:
    f.write("\t".join(HDR) + "\n")
    for i in sorted(final):
        f.write("\t".join(final[i]) + "\n")

# Disagreements: any entry both lenses classed, by class or flag.
d = ["# AET-WO-1219 — where the two lenses disagree", "",
     "Generated by `merge.py`. Lens 1 classed every entry. Lens 2 classed, blind, every K and H-column entry lens 1 had put in N or S, every primitive-typed K entry lens 1 had put in V, the MCU, speed and pin-table columns, and every R entry. "
     "Each disagreement is a finding (CLAUDE.md), settled by the reviewer in `overrides.tsv` or left at lens 1 with the reason given here.", "",
     "| id | lens 1 | lens 2 | final | lens 2's reason | settled by |", "|---|---|---|---|---|---|"]
n = agree = 0
for i, r2 in lens2.items():
    r1 = lens1.get(i)
    if r1 is None:
        print("lens 2 classed an id lens 1 has not: " + i, file=sys.stderr)
        sys.exit(1)
    n += 1
    if (r1[1], r1[2]) == (r2[1], r2[2]):
        agree += 1
        continue
    f = final[i]
    how = "override: " + over[i][5] if i in over else "lens 1 kept"
    d.append("| `%s` | %s%s | %s%s | %s%s | %s | %s |" % (i, r1[1], r1[2], r2[1], r2[2], f[1], f[2], r2[5].replace("|", "\\|"), how.replace("|", "\\|")))
d += ["", "%d entries classed by both lenses; %d agree on class and flag; %d disagree." % (n, agree, n - agree)]
(here / "out" / "disagreements.md").write_text("\n".join(d) + "\n")
print("classes.tsv: %d rows; lens 2 overlap %d, agree %d, disagree %d" % (len(final), n, agree, n - agree))
